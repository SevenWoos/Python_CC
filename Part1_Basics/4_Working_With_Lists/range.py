# range() makes it easy to generate a series of numbers.

# Print 1- 4
for value in range(1, 5):
    print(value)

print('\n')

# Print all numbers from 0 up to 5.
for value in range(6):
    print(value)

print('\n')

# You can convert results of range() to a list of numbers.
numbers = list(range(1, 6))
print(numbers)