# Sometimes we get an arbitrary number.
print(0.2 + 0.1)

print(3 * 0.1)

# When you divide any 2 numbers, even if they are integers, you will get a float.
print(4/2)

# Mixing an integer and a float will also result in a float.
print(1 + 2.0)

print(2 * 3.0)

print(3.0 ** 2)

