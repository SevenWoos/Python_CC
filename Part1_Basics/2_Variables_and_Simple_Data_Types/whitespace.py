# Use rstrip to remove whitestrip from the right of a string.
favorite_language = ' python '
print(favorite_language)

favorite_language.rstrip()
print(favorite_language)


# Use lstrip to remove whitestrip from the left of a string.
favorite_language = ' python '
favorite_language  = favorite_language.lstrip()
favorite_language

# Use strip(0) to remove whitestrip from the left and right of a string.
favorite_language = ' python '
favorite_language.strip()
