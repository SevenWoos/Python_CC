# Checking for inequality.

requested_topping = 'mushrooms'

if requested_topping != 'anchovies':
    print("Hold the anchovies!")

# Check if value is in a list.
requested_toppings = ['mushrooms', 'onions', 'pineapple']
print('mushrooms' in requested_toppings)  # True, because 'mushrooms' is in the list of requested_toppings.
print('pepperoni' in requested_toppings)  # False, because 'pepperoni' is not in the list of requested_toppings.

